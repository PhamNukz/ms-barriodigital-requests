-- Un hito por estado de cada tramite: cuando se cumplio, cuando estima el
-- funcionario que se cumplira y la nota que le deja al vecino. Es lo que muestra
-- el seguimiento desplegable de cada tramite.
CREATE TABLE tramite_hito (
    id              NUMBER(19)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tramite_id      NUMBER(19)     NOT NULL REFERENCES tramite (id),
    estado          VARCHAR2(20)   NOT NULL,
    fecha_cumplido  TIMESTAMP,
    fecha_estimada  TIMESTAMP,
    nota            VARCHAR2(500),
    actualizado_por VARCHAR2(150),
    CONSTRAINT uq_tramite_hito UNIQUE (tramite_id, estado)
);

-- Funcionario que ingreso el tramite a nombre del vecino. Null = lo ingreso el vecino.
ALTER TABLE tramite ADD creado_por VARCHAR2(150);
