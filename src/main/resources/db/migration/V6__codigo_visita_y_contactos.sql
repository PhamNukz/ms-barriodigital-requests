-- Codigo de seguridad de la visita: texto de 4 digitos para no perder los ceros a la izquierda
-- ("0042"). Null en las visitas anteriores a esta version.
-- version: bloqueo optimista. La respuesta del vecino y una reprogramacion simultaneas ya no
-- se pisan en silencio: la segunda recibe 409.
ALTER TABLE visita ADD (
    codigo  VARCHAR2(4),
    version NUMBER(10) DEFAULT 0 NOT NULL
);

-- Familiares que reciben copia (cc) de los avisos del tramite. El maximo de 3 lo controla la app.
-- correo va en minusculas: el UNIQUE frena duplicados aunque cambie la capitalizacion o el
-- vecino haga doble clic.
CREATE TABLE tramite_contacto (
    id          NUMBER(19)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tramite_id  NUMBER(19)     NOT NULL REFERENCES tramite (id),
    nombre      VARCHAR2(100)  NOT NULL,
    correo      VARCHAR2(150)  NOT NULL,
    CONSTRAINT uq_tramite_contacto UNIQUE (tramite_id, correo)
);
