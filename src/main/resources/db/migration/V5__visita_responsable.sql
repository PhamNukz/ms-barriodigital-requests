-- Responsable explicito del tramite (distinto de funcionario_asignado, que es el ultimo
-- que cambio el estado) y momento en que la cuadrilla salio hacia la visita.
-- V4 lo usa la rama del selector de direccion (ubicacion del tramite).
ALTER TABLE tramite ADD (
    responsable     VARCHAR2(150),
    en_camino_desde TIMESTAMP
);

-- Visita en terreno que el funcionario propone y el vecino responde. Una por tramite:
-- reprogramar reemplaza la fila.
CREATE TABLE visita (
    id              NUMBER(19)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tramite_id      NUMBER(19)     NOT NULL REFERENCES tramite (id),
    fecha           DATE           NOT NULL,
    franja          VARCHAR2(10)   NOT NULL,
    cuadrilla       VARCHAR2(100)  NOT NULL,
    nota            VARCHAR2(500),
    estado          VARCHAR2(20)   NOT NULL,
    horario_pedido  VARCHAR2(100),
    actualizado_en  TIMESTAMP      NOT NULL,
    CONSTRAINT uq_visita_tramite UNIQUE (tramite_id)
);
